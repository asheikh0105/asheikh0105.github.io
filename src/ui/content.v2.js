import content from '../../old_site_data/content.json'
import media from './media.v2.json' // generated by scripts/build-media.mjs from photo_vid_uploads/

// Bundles every harvested photo so it's available (and correctly hashed) in
// both dev and production builds, keyed by the same relative path used in
// content.json (e.g. "images/coil-winder/1.jpg").
const imageModules = import.meta.glob('../../old_site_data/images/**/*.{jpg,jpeg,png}', {
  eager: true,
  import: 'default',
})

export function resolveImage(relativePath) {
  if (!relativePath) return null
  return imageModules[`../../old_site_data/${relativePath}`] ?? null
}

const paragraphs = (text) => (text ?? '').split('\n\n').filter(Boolean)

// Every terminal bubble (a project, a design, About, Contact) is normalised to
// the same shape so one detail layout can show any of them:
//   { slug, title, subtitle, date, paragraphs[], images[] (resolved urls), note }
const harvestedProjects = content.projects.map((p) => ({
  slug: p.slug,
  title: p.title,
  subtitle: p.summary,
  paragraphs: paragraphs(p.description),
  images: (p.images ?? []).map(resolveImage).filter(Boolean),
}))

// Projects that were not on the old site. Content to be filled in.
const newProjects = [
  {
    slug: 'self-steering-tricycle',
    title: 'Self-Steering Tricycle',
    subtitle: '',
    paragraphs: [],
    images: [],
  },
]

// Menu order (6 per page). Page 1 ends with the tricycle; the Bar Balancing Car
// starts page 2. Anything not listed keeps its content.json order after these.
const PROJECT_ORDER = [
  'lqr-inverted-pendulum-balancer',
  'clawd-wirelessly-controlled-3-5-dof-mechanism',
  'self-steering-tricycle',
  'analysis-2nd-order-system-linear-potentiometer',
  'coil-winder',
  'linear-motor-control-soft-robotic-actuators',
  'bar-balancing-car',
]
const rank = (p) => {
  const i = PROJECT_ORDER.indexOf(p.slug)
  return i === -1 ? PROJECT_ORDER.length : i
}
// Uploaded media (photo_vid_uploads/<slug>/) wins over the old-site photos:
// thumbnail first in the carousel, then the rest; videos are shown separately.
const withMedia = (p) => {
  const m = media[p.slug]
  if (!m) return { ...p, videos: [] }
  return { ...p, thumb: m.thumb, images: m.images, videos: m.videos }
}
// A project with nothing to show (no summary, text, photos or video) is left out
// rather than shown as an empty page.
const hasContent = (p) => p.subtitle || p.paragraphs.length || p.images.length || p.videos.length
const projects = [...harvestedProjects, ...newProjects]
  .map(withMedia)
  .filter(hasContent)
  .sort((a, b) => rank(a) - rank(b)) // stable

const harvestedDesigns = content.models_and_designs.items.map((d) => ({
  slug: d.slug,
  title: d.title,
  paragraphs: paragraphs(d.description),
  images: (d.images ?? []).map(resolveImage).filter(Boolean),
}))

// Designs not on the old site. Content to be filled in (photos go in
// photo_vid_uploads/<slug>/).
const newDesigns = [
  { slug: 'linear-actuator-steering-mechanism', title: 'Linear Actuator Steering Mechanism', paragraphs: [], images: [] },
  { slug: 'electronics-mounting-rack', title: 'Electronics Mounting Rack', paragraphs: [], images: [] },
]

// Menu order (6 per page): the steering mechanism is first, so its photo becomes
// the Designs bubble on the home page; the rest keep content.json order.
const DESIGN_ORDER = ['linear-actuator-steering-mechanism', 'electronics-mounting-rack']
const designRank = (d) => {
  const i = DESIGN_ORDER.indexOf(d.slug)
  return i === -1 ? DESIGN_ORDER.length : i
}

// Per-design thumbnail tweaks. thumbZoom < 1 zooms the bubble picture out
// (whole picture, scaled, on white) instead of cropping it to fill.
// Bubble only: the picture shown on the design's own page is never scaled.
const DESIGN_TWEAKS = {
  'wheel-and-tire-assembly': { thumbZoom: 0.95 },
  'electronics-mounting-rack': { thumbZoom: 0.95 },
  'helmet-holder': { thumbZoom: 0.975 },
  'linear-actuator-steering-mechanism': { thumbZoom: 0.975 },
}

const designs = [...harvestedDesigns, ...newDesigns]
  .map(withMedia)
  .map((d) => ({ ...d, ...DESIGN_TWEAKS[d.slug] }))
  .sort((a, b) => designRank(a) - designRank(b)) // stable

// About Me: photos come from photo_vid_uploads/about/ (aamirPicture = thumbnail,
// then the two certificates). The old site's profile photo is no longer used here.
const aboutMedia = media.about
const about = {
  slug: 'about',
  title: 'About Me',
  subtitle: content.about.certifications,
  paragraphs: content.about.bio,
  thumb: aboutMedia?.thumb,
  images: aboutMedia?.images ?? [],
  videos: [],
}

// Contact: filler text for now. Replace with the real details before going live.
const contact = {
  slug: 'contact',
  title: 'Contact',
  paragraphs: ['Contact details coming soon.', 'Email, LinkedIn and GitHub links will go here.'],
  images: [],
}

export const sections = { projects, designs }
export const terminals = { about, contact }

// Picture (and zoom) a home bubble borrows from an item; Projects uses the
// tricycle's thumbnail, Designs the first design that has a photo.
const bubbleFace = (item) => ({ thumb: item?.thumb ?? item?.images[0], thumbZoom: item?.thumbZoom })

// The home screen bubbles: Projects, Designs, About Me (tall, right).
export const homeBubbles = [
  { key: 'projects', label: 'Projects', kind: 'ring', ...bubbleFace(projects.find((p) => p.slug === 'self-steering-tricycle')) },
  { key: 'designs', label: 'Designs', kind: 'ring', ...bubbleFace(designs.find((d) => d.images[0])) },
  { key: 'about', label: 'About Me', kind: 'terminal', thumb: about.thumb ?? about.images[0] },
  // Contact bubble removed from home for now (page content kept in `contact` above).
]

// Detail pages show pictures and video as separate panels. With a video and only a
// thumbnail's worth of photos there is no carousel (the video is the panel).
export const hasPhotoCarousel = (item) => item.images.length > 0 && !((item.videos ?? []).length > 0 && item.images.length <= 1)
export const hasSmallVideo = (item) => hasPhotoCarousel(item) && (item.videos ?? []).length > 0
